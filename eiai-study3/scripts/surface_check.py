#!/usr/bin/env python3
"""Surface comparison of each strong/weak pair in the v3 stimulus set.

The v3 specification says the two versions of a claim are matched on length
(±10 %) and number of sentences, figures and named sources. This measures the
parts of that which can be counted mechanically and reports them. It changes
nothing: the texts are approved, and deciding what to do about a mismatch is
the researcher's call, not a script's.

    python scripts/surface_check.py        # writes docs/SURFACE_CHECK_v3.md

Counts
------
- words: whitespace-separated tokens containing a letter or digit
- sentences: split after . ! ? before a capital or a quote -- the same rule
  the shared-first-sentence test uses
- figures: numbers as written ("3%", "1–1.5", "28,000" count once each)
- digits: digit characters
- length: characters

A pair is flagged when the character length or the word count differs by more
than 10 % of the strong version, or when the sentence counts differ.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "pipeline"))

import stimuli_v3  # noqa: E402

OUT = ROOT / "docs" / "SURFACE_CHECK_v3.md"
THRESHOLD = 10.0

FIGURE = re.compile(r"\d[\d,.]*(?:\s?[–-]\s?\d[\d,.]*)?")


def words(text: str) -> int:
    return sum(1 for token in text.split() if re.search(r"[A-Za-z0-9]", token))


def figures(text: str) -> int:
    return len(FIGURE.findall(text))


def measure(text: str) -> dict[str, int]:
    return {
        "chars": len(text),
        "words": words(text),
        "sentences": len(stimuli_v3.split_sentences(text)),
        "figures": figures(text),
        "digits": sum(ch.isdigit() for ch in text),
    }


def pct(strong: int, weak: int) -> float:
    return (weak - strong) / strong * 100 if strong else 0.0


def rows() -> list[dict]:
    explanations = stimuli_v3.build()[stimuli_v3.EXPLANATIONS]["explanations"]
    pairs: dict[str, dict[str, dict]] = {}
    for e in explanations:
        pairs.setdefault(e["claim_id"], {})[e["version"]] = e
    out = []
    for claim_id in sorted(pairs):
        strong = measure(pairs[claim_id]["strong"]["text"])
        weak = measure(pairs[claim_id]["weak"]["text"])
        char_diff = pct(strong["chars"], weak["chars"])
        word_diff = pct(strong["words"], weak["words"])
        reasons = []
        if abs(char_diff) > THRESHOLD:
            reasons.append(f"length {char_diff:+.1f}%")
        if abs(word_diff) > THRESHOLD:
            reasons.append(f"words {word_diff:+.1f}%")
        if strong["sentences"] != weak["sentences"]:
            reasons.append(f"sentences {strong['sentences']} vs {weak['sentences']}")
        out.append({
            "claim_id": claim_id,
            "module": pairs[claim_id]["strong"]["module"],
            "strong": strong,
            "weak": weak,
            "char_diff": char_diff,
            "word_diff": word_diff,
            "flags": reasons,
        })
    return out


def render(data: list[dict]) -> str:
    lines = [
        "# Surface check — v3 explanations",
        "",
        "Generated by `python scripts/surface_check.py`. A report only: no text was changed.",
        "",
        f"A pair is flagged when character length or word count differs by more than "
        f"{THRESHOLD:.0f} % of the strong version, or when the number of sentences differs. "
        "Differences are weak minus strong, as a percentage of strong.",
        "",
        "| Claim | Module | Words S / W | Sentences S / W | Figures S / W | Digits S / W | Chars S / W | Length Δ | Words Δ | Flag |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in data:
        s, w = r["strong"], r["weak"]
        flag = "**" + "; ".join(r["flags"]) + "**" if r["flags"] else "—"
        lines.append(
            f"| {r['claim_id']} | {r['module']} | {s['words']} / {w['words']} | "
            f"{s['sentences']} / {w['sentences']} | {s['figures']} / {w['figures']} | "
            f"{s['digits']} / {w['digits']} | {s['chars']} / {w['chars']} | "
            f"{r['char_diff']:+.1f}% | {r['word_diff']:+.1f}% | {flag} |"
        )
    flagged = [r for r in data if r["flags"]]
    lines += ["", "## Flagged pairs", ""]
    if not flagged:
        lines.append("None.")
    for r in flagged:
        lines.append(f"- **{r['claim_id']}** (module {r['module']}): " + "; ".join(r["flags"]))
    lines += [
        "",
        "Figures count numbers as written, so `1–1.5%` is one figure. Named sources are not "
        "counted here: telling a source from any other proper noun needs a reader, not a regex.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    data = rows()
    OUT.write_text(render(data), encoding="utf-8", newline="\n")
    flagged = [r for r in data if r["flags"]]
    print(f"Wrote {OUT.relative_to(ROOT)}: {len(flagged)} of {len(data)} pairs flagged.")
    for r in flagged:
        print(f"  {r['claim_id']}: " + "; ".join(r["flags"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
