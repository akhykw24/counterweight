#!/usr/bin/env python3
"""The v3 main-study allocation sequence, and the SQL that serves it.

Permuted blocks of four within each English-level stratum: every block holds
each cell -- EI-A, EI-B, Neutral-A, Neutral-B -- exactly once, in an order
drawn from a committed seed. The four cells therefore stay balanced at every
block boundary, in each stratum separately, rather than only in expectation.

The pilot did not stratify by English level (brief, step 3: "record it, do not
stratify on it in the pilot"); the main study does, with the same two bands
the deep-sea design used: B1-B2 and C1-C2/native.

Why the server hands out the slots
----------------------------------
Every earlier allocation in this project was computed in the browser, from a
hash of the session id or from a number in the link. A hash balances only in
expectation -- two people who start in the same minute can draw the same cell
-- and a single public link has no number in it. So the sequence is loaded
into the database (services/ingest/sql/004_v3_allocation.sql, generated
here) and `claim_v3_slot()` gives each session the next unclaimed slot of its
stratum, atomically. A session that asks again (a reload, a retry after a
dropped connection) gets the slot it already holds.

Test runs (`test=true` without `cell=`) draw from a separate sequence, under
strata prefixed `test:`, with its own seed. They exercise exactly the code
path a participant does without ever consuming a participant's slot.

The sequence is generated once and committed, and its digest is recorded in
docs/allocation-v3-precommit.txt, so a reader can verify afterwards that the
randomisation was fixed in advance and not adjusted.

Usage
-----
    python pipeline/allocation_v3.py           # write the JSON, the SQL and the pre-commitment
    python pipeline/allocation_v3.py --check   # fail if any of them is stale or edited
"""

from __future__ import annotations

import argparse
import json
import random
import sys
from pathlib import Path
from typing import Any, Iterable

from _common import REPO_ROOT, canonical_json, sha256_text

SEED = 20261017
TEST_SEED = 20261018

CELLS = ("EI-A", "EI-B", "Neutral-A", "Neutral-B")
STRATA = ("B1-B2", "C1-C2-native")
TEST_PREFIX = "test:"
BLOCK_SIZE = len(CELLS)
#: Capacity, not a target: 100 blocks of four per stratum. The target sample
#: size comes from the power analysis; slots that are never claimed cost
#: nothing, while a stratum that runs out stops recruitment.
BLOCKS_PER_STRATUM = 100
TEST_BLOCKS_PER_STRATUM = 50

JSON_PATH = REPO_ROOT / "materials" / "allocation-v3.json"
SQL_PATH = REPO_ROOT / "services" / "ingest" / "sql" / "004_v3_allocation.sql"
PRECOMMIT_PATH = REPO_ROOT / "docs" / "allocation-v3-precommit.txt"


def build_sequence(seed: int, strata: Iterable[str], blocks: int) -> dict[str, list[str]]:
    """One shuffled block of the four cells after another, per stratum."""
    rng = random.Random(seed)
    sequence: dict[str, list[str]] = {}
    for stratum in strata:
        cells: list[str] = []
        for _ in range(blocks):
            block = list(CELLS)
            rng.shuffle(block)
            cells.extend(block)
        sequence[stratum] = cells
    return sequence


def digest(sequence: dict[str, list[str]]) -> str:
    return sha256_text(canonical_json(sequence))


def build_document() -> dict[str, Any]:
    live = build_sequence(SEED, STRATA, BLOCKS_PER_STRATUM)
    test = build_sequence(TEST_SEED, [TEST_PREFIX + s for s in STRATA], TEST_BLOCKS_PER_STRATUM)
    return {
        "version": "v3",
        "design": "permuted blocks of four within English-level strata",
        "cells": list(CELLS),
        "block_size": BLOCK_SIZE,
        "seed": SEED,
        "strata": list(STRATA),
        "sequence": live,
        "sequence_sha256": digest(live),
        "test_seed": TEST_SEED,
        "test_sequence": test,
        "test_sequence_sha256": digest(test),
    }


def _values(sequence: dict[str, list[str]]) -> list[str]:
    return [
        f"    ('{stratum}', {index}, '{cell}')"
        for stratum, cells in sequence.items()
        for index, cell in enumerate(cells)
    ]


def build_sql(document: dict[str, Any]) -> str:
    rows = _values(document["sequence"]) + _values(document["test_sequence"])
    cells = ", ".join(f"'{c}'" for c in CELLS)
    return f"""-- v3 main-study allocation: GENERATED by pipeline/allocation_v3.py -- do not edit.
--
-- Permuted blocks of four within each English-level stratum, from seed
-- {document['seed']} (sequence_sha256 {document['sequence_sha256']}),
-- plus a separate test sequence under strata prefixed 'test:' (seed
-- {document['test_seed']}). See docs/allocation-v3-precommit.txt.
--
-- claim_v3_slot(session, stratum) gives a session the lowest unclaimed slot of
-- its stratum, atomically: two participants who start at the same moment get
-- different slots. A session that asks again gets the slot it already holds,
-- so a reload or a retried request can never move anyone to another cell.
--
-- This table is operational state, not the study record: claiming a slot
-- updates its row. The study record stays the append-only event log, where
-- every `allocation` event carries the cell and the slot index it received,
-- so the realised assignment can always be checked against the sequence.
--
-- Paste into Supabase -> SQL Editor -> Run. Safe to run twice: existing
-- claims are never touched, and the script stops with an error if the slots
-- already in the table disagree with this sequence.

create table if not exists public.v3_allocation_slots (
    stratum    text        not null,
    idx        integer     not null check (idx >= 0),
    cell       text        not null check (cell in ({cells})),
    session_id uuid        unique,
    claimed_at timestamptz,
    primary key (stratum, idx)
);

alter table public.v3_allocation_slots enable row level security;
revoke all on public.v3_allocation_slots from anon, authenticated;

create or replace function public.claim_v3_slot(p_session uuid, p_stratum text)
returns table (idx integer, cell text)
language plpgsql
security definer
set search_path = public
as $$
declare
    held record;
begin
    -- Idempotent: a session that already holds a slot gets that one back.
    select s.idx, s.cell into held
    from public.v3_allocation_slots s
    where s.session_id = p_session;
    if found then
        return query select held.idx, held.cell;
        return;
    end if;

    -- The lowest free slot of the stratum. SKIP LOCKED: a slot being claimed
    -- by a concurrent request is passed over rather than waited on, so two
    -- simultaneous requests can never receive the same slot.
    with next_slot as (
        select s.stratum, s.idx
        from public.v3_allocation_slots s
        where s.stratum = p_stratum and s.session_id is null
        order by s.idx
        limit 1
        for update skip locked
    )
    update public.v3_allocation_slots s
    set session_id = p_session, claimed_at = now()
    from next_slot
    where s.stratum = next_slot.stratum and s.idx = next_slot.idx
    returning s.idx, s.cell into held;

    if not found then
        raise exception 'v3 allocation sequence exhausted for stratum %', p_stratum
            using errcode = 'P0001', hint = 'exhausted';
    end if;
    return query select held.idx, held.cell;
end;
$$;

-- Counts only. Says how many have started, never which cell comes next.
create or replace function public.v3_allocation_status()
returns table (stratum text, claimed bigint, total bigint)
language sql
security definer
set search_path = public
as $$
    select s.stratum, count(s.session_id), count(*)
    from public.v3_allocation_slots s
    group by s.stratum
    order by s.stratum;
$$;

revoke all on function public.claim_v3_slot(uuid, text) from public, anon, authenticated;
revoke all on function public.v3_allocation_status() from public, anon, authenticated;
grant execute on function public.claim_v3_slot(uuid, text) to service_role;
grant execute on function public.v3_allocation_status() to service_role;

-- A plain temporary table, dropped explicitly: `on commit drop` would vanish
-- straight after its own statement in an editor that commits each statement.
drop table if exists pg_temp.v3_expected;
create temporary table v3_expected (stratum text, idx integer, cell text);
insert into v3_expected (stratum, idx, cell) values
{(","+chr(10)).join(rows)};

insert into public.v3_allocation_slots (stratum, idx, cell)
select stratum, idx, cell from v3_expected
on conflict (stratum, idx) do nothing;

do $$
begin
    if exists (
        select 1
        from public.v3_allocation_slots s
        join v3_expected e using (stratum, idx)
        where s.cell <> e.cell
    ) then
        raise exception 'v3_allocation_slots holds a different sequence from this file; nothing was changed';
    end if;
end;
$$;

drop table if exists pg_temp.v3_expected;

notify pgrst, 'reload schema';

-- Check: one row per stratum, nothing claimed yet.
select * from public.v3_allocation_status();
"""


def build_precommit(document: dict[str, Any]) -> str:
    lines = [
        "Allocation pre-commitment -- v3 main study",
        "==========================================",
        "",
        "Recorded BEFORE main-study data collection opens. The sequence itself is",
        "in materials/allocation-v3.json and is served by",
        "services/ingest/sql/004_v3_allocation.sql; this file records its digest so",
        "a reader can verify afterwards that the randomisation was not adjusted.",
        "",
        f"design            {document['design']}",
        f"seed              {document['seed']}",
        f"sequence_sha256   {document['sequence_sha256']}",
        "",
        "Per stratum:",
    ]
    for stratum, cells in document["sequence"].items():
        counts = " / ".join(f"{cells.count(c)} {c}" for c in CELLS)
        lines.append(f"  {stratum:<14} {len(cells)} slots  ({counts})")
    lines += [
        "",
        "Test runs draw from a separate sequence (strata prefixed 'test:',",
        f"seed {document['test_seed']}, sha256 {document['test_sequence_sha256']}),",
        "so rehearsals never consume a participant's slot.",
        "",
        "The pilot used its own rotation (docs/LINKS_v3.md) and none of this.",
        "",
        "Verify with:",
        "",
        "    python pipeline/allocation_v3.py --check",
        "",
    ]
    return "\n".join(lines)


def outputs() -> dict[Path, str]:
    document = build_document()
    return {
        JSON_PATH: canonical_json(document),
        SQL_PATH: build_sql(document),
        PRECOMMIT_PATH: build_precommit(document),
    }


def check() -> list[str]:
    problems = []
    for path, expected in outputs().items():
        if not path.exists():
            problems.append(f"{path.relative_to(REPO_ROOT)} is missing")
        elif path.read_text(encoding="utf-8").replace("\r\n", "\n") != expected:
            problems.append(f"{path.relative_to(REPO_ROOT)} does not match a fresh generation")
    return problems


def main(argv: Iterable[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build or check the v3 allocation sequence.")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(list(argv) if argv is not None else None)
    if args.check:
        problems = check()
        if problems:
            for p in problems:
                print(f"  - {p}", file=sys.stderr)
            return 1
        document = json.loads(JSON_PATH.read_text(encoding="utf-8"))
        print(f"v3 allocation is current: seed {document['seed']}, sequence_sha256 {document['sequence_sha256']}")
        return 0
    for path, text in outputs().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {JSON_PATH.name}, {SQL_PATH.name} and {PRECOMMIT_PATH.name}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
