#!/usr/bin/env python3
"""Assemble the results document (spec section 10, day 7).

Takes the analysis output, the specification curve and the provenance hashes and
writes a single self-contained HTML file. `make paper` then prints it to PDF
with the Chromium that Playwright already installs, which avoids adding a LaTeX
toolchain to the image for one document.

Everything in the output is derived. Nothing is typed in by hand, so a number in
the document that disagrees with the pipeline is impossible rather than merely
unlikely -- which is the property `make paper` from a clean clone is supposed to
demonstrate.

Usage
-----
    python pipeline/report.py --results data/results.json \
        --multiverse data/multiverse --out paper/results.html

Exit codes: 0 ok, 2 missing input.
"""

from __future__ import annotations

import argparse
import base64
import csv
import json
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Iterable

from _common import MANIFEST_JSON, MATERIALS, REPO_ROOT, read_json, sha256_file

