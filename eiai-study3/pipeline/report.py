def _fmt(value: Any, places: int = 3) -> str:
    if value is None:
        return "—"
    try:
        number = float(value)
    except (TypeError, ValueError):
        return str(value)
    if number != number:  # NaN
        return "—"
    return f"{number:.{places}f}"


def _rows(pairs: Iterable[tuple[str, str]]) -> str:
    return "".join(
        f"<tr><td>{label}</td><td class='num'>{value}</td></tr>" for label, value in pairs
    )


def build_html(results: dict[str, Any], multiverse_rows: list[dict[str, str]],
               curve_png: Path | None) -> str:
    n = results["n"]
    desc = results["descriptives"]
    h1, h2 = results["H1_interaction"], results["H2_vigilance"]
    h3, h4, h5 = results["H3_discrimination"], results["H4_mediation"], results["H5_trust"]
    recovery = results.get("recovery")

    manifest = read_json(MANIFEST_JSON) if MANIFEST_JSON.exists() else {}
    allocation_path = MATERIALS / "allocation.json"
    allocation = read_json(allocation_path) if allocation_path.exists() else {}

    parts: list[str] = [
        "<title>Study 3 — results</title>",
        f"<style>{STYLE}</style>",
        "<h1>Emotional Warmth as a Peripheral Cue</h1>",
        "<p class='subtitle'>Processing-route displacement in human–AI epistemic "
        "interaction — automated results document</p>",
        "<div class='note'><strong>These are results from synthetic participants.</strong> "
        "This document is generated by <code>make paper</code> from the simulation bots so "
        "that the analysis pipeline can be exercised end to end before any human is "
        "recruited. Every number below is derived from the event log; none is entered by "
        "hand. Running the same command against real collected data produces the same "
        "document with the same code path.</div>",
    ]

    parts.append("<h2>Sample</h2><table>")
    parts.append("<tr><th>Quantity</th><th>Value</th></tr>")
    parts.append(_rows([
        ("Participants", str(n["participants"])),
        ("Warm arm", str(n["warm"])),
        ("Neutral arm", str(n["neutral"])),
        ("Trials used", f"{n['trials_used']} of {n['trials_available']}"),
        ("Specification", f"<code>{results['specification']['label']}</code>"),
    ]))
    parts.append("</table>")

    checks = results.get("manipulation_checks")
    if checks:
        # Placed before the hypotheses on purpose. If the warmth manipulation
        # did not land, nothing below it is interpretable, and a reader should
        # learn that before reading a p-value.
        warmth = checks["warmth"]
        competence = checks["competence"]
        parts.append("<h2>Manipulation and control checks</h2><table>")
        parts.append(
            "<tr><th>Scale</th><th>Expected</th><th class='num'>Difference</th>"
            "<th class='num'>Evidence</th><th>Verdict</th></tr>"
        )
        parts.append(
            f"<tr><td>Perceived warmth</td><td>warm &gt; neutral</td>"
            f"<td class='num'>{_fmt(warmth['diff'])}</td>"
            f"<td class='num'>p = {_fmt(warmth['p'], 4)}</td>"
            f"<td>{'pass' if warmth['passed'] else 'FAIL'}</td></tr>"
        )
        parts.append(
            f"<tr><td>Perceived competence</td><td>no difference</td>"
            f"<td class='num'>{_fmt(competence['diff'])}</td>"
            f"<td class='num'>BF<sub>01</sub> = {_fmt(competence['bf01'], 2)}</td>"
            f"<td>{'pass' if competence['passed'] else 'FAIL'}</td></tr>"
        )
        parts.append("</table>")
        parts.append(
            "<p>The control check is judged by evidence <em>for</em> the null rather "
            "than by a non-significant p-value: failing to reject is not evidence of "
            "absence, and a p-based control is easiest to pass with a sample too small "
            "to say anything.</p>"
        )

    exclusions = results.get("exclusions")
    if exclusions:
        # Per criterion, never as a single total. An aggregate "18 excluded"
        # is unauditable: it hides whether the sample lost non-completers or
        # lost the people who disagreed with the advice.
        parts.append("<h2>Exclusions</h2>")
        parts.append(
            "<p>Specification section 8.6, applied as a separate pipeline step. "
            f"{exclusions['n_excluded']} of {exclusions['n_participants']} participants "
            f"flagged; {exclusions['n_retained']} retained. Every test above is reported "
            "on the unexcluded sample; the excluded-sample figures are in "
            "<code>results.json</code> under <code>with_exclusions</code>.</p>"
        )
        parts.append("<table>")
        parts.append("<tr><th>#</th><th>Criterion</th><th class='num'>Excluded</th></tr>")
        for criterion in exclusions["criteria"]:
            label = criterion["label"]
            if not criterion["applied"]:
                label += " <em>(declared, not applied)</em>"
            parts.append(
                f"<tr><td>{criterion['number']}</td><td>{label}</td>"
                f"<td class='num'>{criterion['n_excluded']}</td></tr>"
            )
        parts.append("</table>")
        parts.append(
            "<p>Participants can be flagged by more than one criterion, so the column "
            "sums to at least the number excluded.</p>"
        )

    parts.append("<h2>Weight of Advice</h2><table>")
    parts.append("<tr><th>Arm</th><th class='num'>strong</th><th class='num'>weak</th>"
                 "<th class='num'>discrimination</th></tr>")
    for arm in ("warm", "neutral"):
        parts.append(
            f"<tr><td>{arm}</td>"
            f"<td class='num'>{_fmt(desc[f'woa_strong_{arm}'])}</td>"
            f"<td class='num'>{_fmt(desc[f'woa_weak_{arm}'])}</td>"
            f"<td class='num'>{_fmt(desc[f'discrimination_{arm}'])}</td></tr>"
        )
    parts.append("</table>")
    parts.append(
        "<p>Discrimination is <code>WOA(strong) − WOA(weak)</code> within participant. "
        "The prediction is that it is <em>smaller</em> in the warm arm: warmth displaces "
        "processing off the argument and onto the cue.</p>"
    )

    parts.append("<h2>Confirmatory tests</h2><table>")
    parts.append("<tr><th>Hypothesis</th><th>Statistic</th><th class='num'>p</th>"
                 "<th>Effect</th></tr>")
    parts.append(
        f"<tr><td>H1 style × quality interaction</td>"
        f"<td>F({h1['df1']:.0f}, {h1['df2']:.0f}) = {_fmt(h1['F'])}</td>"
        f"<td class='num'>{_fmt(h1['p'], 4)}</td>"
        f"<td>partial η² = {_fmt(h1['partial_eta_sq'])}</td></tr>"
        f"<tr><td>H2 vigilance composite</td>"
        f"<td>t({_fmt(h2['df'], 1)}) = {_fmt(h2['t'])}</td>"
        f"<td class='num'>{_fmt(h2['p'], 4)}</td>"
        f"<td>Δ = {_fmt(h2['diff'])}</td></tr>"
        f"<tr><td>H3 discrimination, warm − neutral</td>"
        f"<td>t({_fmt(h3['df'], 1)}) = {_fmt(h3['t'])}</td>"
        f"<td class='num'>{_fmt(h3['p'], 4)}</td>"
        f"<td>Δ = {_fmt(h3['diff'])} [{_fmt(h3['ci_low'])}, {_fmt(h3['ci_high'])}], "
        f"g = {_fmt(h3['hedges_g'])}</td></tr>"
        f"<tr><td>H4 scroll-depth mediation</td>"
        f"<td>indirect = {_fmt(h4['indirect'], 4)}</td><td class='num'>—</td>"
        f"<td>95% CI [{_fmt(h4['ci_low'], 4)}, {_fmt(h4['ci_high'], 4)}]</td></tr>"
        f"<tr><td>H5 trust, warm − neutral</td>"
        f"<td>t({_fmt(h5['df'], 1)}) = {_fmt(h5['t'])}</td>"
        f"<td class='num'>{_fmt(h5['p'], 4)}</td>"
        f"<td>Δ = {_fmt(h5['diff'])}</td></tr>"
    )
    parts.append("</table>")

    consistent = results.get("h1_h3_consistent")
    parts.append(
        f"<p>H1 and H3 are the same test expressed two ways — with two within-subject "
        f"levels the interaction reduces to a between-groups contrast on the difference "
        f"score, so <code>F = t²</code>. Identity check: "
        f"<span class='{'pass' if consistent else 'fail'}'>"
        f"{'holds' if consistent else 'FAILS — one of the two is computed wrongly'}</span>.</p>"
    )

    parts.append(
        f"<h3>Bayes factor</h3><p>BF<sub>10</sub> = <strong>{_fmt(h3['bf10'])}</strong> "
        f"on H3 (JZS, Cauchy prior r = 0.707). The pre-registered sequential rule stops at "
        f"BF<sub>10</sub> &gt; 6 or &lt; 1/6, first look at N = 60 and every 20 thereafter, "
        f"hard cap N = 160.</p>"
    )

    parts.append("<h3>Holm–Bonferroni across secondaries</h3><table>")
    parts.append("<tr><th>Test</th><th class='num'>p</th><th class='num'>p<sub>Holm</sub></th>"
                 "<th>Outcome</th></tr>")
    for name, entry in sorted(results["holm"].items()):
        mark = ("<span class='pass'>survives</span>" if entry["survives"]
                else "<span class='fail'>does not survive</span>")
        parts.append(f"<tr><td>{name}</td><td class='num'>{_fmt(entry['p'], 4)}</td>"
                     f"<td class='num'>{_fmt(entry['p_holm'], 4)}</td><td>{mark}</td></tr>")
    parts.append("</table>")

    if multiverse_rows:
        excludes_neg = sum(1 for r in multiverse_rows if _float(r["ci_high"]) < 0)
        excludes_pos = sum(1 for r in multiverse_rows if _float(r["ci_low"]) > 0)
        estimates = sorted(_float(r["estimate"]) for r in multiverse_rows)
        median = estimates[len(estimates) // 2]
        parts.append("<h2>Specification curve</h2>")
        parts.append(
            f"<p>All {len(multiverse_rows)} defensible specifications — clamp range, "
            f"denominator threshold, suspicious-participant handling, resumed-session "
            f"handling and reaction-time trimming. Median estimate "
            f"<strong>{_fmt(median)}</strong>, range {_fmt(estimates[0])} to "
            f"{_fmt(estimates[-1])}. Intervals excluding zero: "
            f"<strong>{excludes_neg}</strong> in the predicted direction, "
            f"<strong>{excludes_pos}</strong> against it.</p>"
        )
        if curve_png and curve_png.exists():
            encoded = base64.b64encode(curve_png.read_bytes()).decode("ascii")
            parts.append(
                f"<figure><img src='data:image/png;base64,{encoded}' "
                f"alt='Specification curve'>"
                f"<figcaption>Every specification, sorted by estimate. The lower panel "
                f"shows which choice each one made, so a result that depends on a single "
                f"decision is visible rather than buried.</figcaption></figure>"
            )

    if recovery:
        parts.append("<h2>Parameter recovery</h2>")
        parts.append(
            "<p>Synthetic participants were generated with known effects. The pipeline "
            "has to return them; if it cannot, it would have mis-estimated real data the "
            "same way.</p><table>"
        )
        parts.append("<tr><th>Policy</th><th>Quantity</th><th class='num'>planted</th>"
                     "<th class='num'>recovered</th></tr>")
        for policy, entry in sorted(recovery["per_policy"].items()):
            disc, style = entry["recovered_discrimination"], entry["recovered_style_effect"]
            parts.append(
                f"<tr><td rowspan='3'>{policy}</td><td>discrimination</td>"
                f"<td class='num'>{_fmt(entry['planted_quality_effect'])}</td>"
                f"<td class='num'>{_fmt(disc['estimate'])} "
                f"[{_fmt(disc['ci_low'])}, {_fmt(disc['ci_high'])}]</td></tr>"
                f"<tr><td>style effect</td>"
                f"<td class='num'>{_fmt(entry['planted_style_effect'])}</td>"
                f"<td class='num'>{_fmt(style['estimate'])} "
                f"[{_fmt(style['ci_low'])}, {_fmt(style['ci_high'])}]</td></tr>"
                f"<tr><td>scroll depth</td>"
                f"<td class='num'>{_fmt(entry['planted_scroll_mean'])}</td>"
                f"<td class='num'>{_fmt(entry['recovered_scroll_mean'])}</td></tr>"
            )
        parts.append("</table><table>")
        parts.append("<tr><th>Check</th><th>Result</th></tr>")
        for finding in recovery["checks"]:
            mark = ("<span class='pass'>ok</span>" if finding["ok"]
                    else "<span class='fail'>FAIL</span>")
            parts.append(f"<tr><td>{finding['check']}</td><td>{mark}</td></tr>")
        parts.append("</table>")

    parts.append("<h2>Provenance</h2><table>")
    parts.append("<tr><th>Artefact</th><th>Digest / value</th></tr>")
    provenance = [
        ("Stimulus manifest", manifest.get("manifest_sha256", "—")),
        ("Stimulus generator mode", manifest.get("generator_mode", "—")),
        ("Stimulus provider / model",
         f"{manifest.get('provider', '—')} / {manifest.get('model', '—')}"),
        ("Launch ready", str(manifest.get("launch_ready", "—"))),
        ("Item bank", sha256_file(MATERIALS / "items.json")
         if (MATERIALS / "items.json").exists() else "—"),
        ("Allocation sequence", allocation.get("sequence_sha256", "—")),
        ("Allocation seed", str(allocation.get("seed", "—"))),
    ]
    for label, value in provenance:
        parts.append(f"<tr><td>{label}</td><td class='hash'>{value}</td></tr>")
    parts.append("</table>")

    if not manifest.get("launch_ready", False):
        parts.append(
            "<div class='note'><strong>The stimulus set in this build is not launch "
            "ready.</strong> <code>launch_ready</code> is false, which means the frozen "
            "responses are offline placeholders rather than generated material. The "
            "pipeline is exercised correctly; the stimuli are not collection material.</div>"
        )

    generated = datetime.now(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z")
    parts.append(f"<p class='subtitle'>Generated {generated} by "
                 f"<code>pipeline/report.py</code>.</p>")
    return "\n".join(parts)


def _float(value: Any) -> float:
    try:
        return float(value)
    except (TypeError, ValueError):
        return float("nan")


def main(argv: Iterable[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Assemble the results document.")
    parser.add_argument("--results", default=str(REPO_ROOT / "data" / "results.json"))
    parser.add_argument("--multiverse", default=str(REPO_ROOT / "data" / "multiverse"))
    parser.add_argument("--out", default=str(REPO_ROOT / "paper" / "results.html"))
    args = parser.parse_args(list(argv) if argv is not None else None)

    results_path = Path(args.results)
    if not results_path.exists():
        print(f"{results_path} not found -- run pipeline/analysis.py --json first",
              file=sys.stderr)
        return 2
    results = json.loads(results_path.read_text(encoding="utf-8"))

    multiverse_dir = Path(args.multiverse)
    curve_csv = multiverse_dir / "specification_curve.csv"
    rows: list[dict[str, str]] = []
    if curve_csv.exists():
        rows = list(csv.DictReader(curve_csv.open(encoding="utf-8")))

    html = build_html(results, rows, multiverse_dir / "specification_curve.png")
    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(html, encoding="utf-8", newline="\n")
    print(f"Results document -> {out_path} ({len(html):,} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
